import { act, render, screen, waitFor } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { beforeEach, expect, it, vi } from "vitest";
import type { FixArchivePage } from "@/lib/types";
const mocks = vi.hoisted(() => ({ list: vi.fn() }));
vi.mock("@/lib/fixWorkspaceApi", () => ({ listArchivedFixWorkspaces: mocks.list }));
import { FixWorkspaceArchive } from "./FixWorkspaceArchive";
const entry = (id: string, title: string) => ({ id, title, repositoryId: 1, branch: `fix/cvec-${id}`, archivedAt: "2026-11-10T00:00:00Z" });
beforeEach(() => vi.resetAllMocks());
it("replaces summary pages, returns to earlier pages and opens only the selected record", async () => {
  const first = entry("a".repeat(24), "First saved task");
  const second = entry("b".repeat(24), "Second saved task");
  mocks.list.mockImplementation(async (_id, cursor) => ({ entries: [cursor ? second : first], nextCursor: cursor ? null : "next-cursor" }));
  const select = vi.fn(); const close = vi.fn();
  render(<FixWorkspaceArchive repositoryId={1} open onOpenChange={close} onSelect={select} />);
  await screen.findByText(first.title);
  await userEvent.click(screen.getByRole("button", { name: "Next page" }));
  await screen.findByText(second.title);
  expect(screen.queryByText(first.title)).not.toBeInTheDocument();
  expect(mocks.list).toHaveBeenLastCalledWith(1, "next-cursor", undefined);
  await userEvent.click(screen.getByRole("button", { name: "Previous page" }));
  await screen.findByText(first.title);
  await userEvent.click(screen.getByRole("button", { name: /First saved task/ }));
  expect(select).toHaveBeenCalledWith(first.id);
  expect(close).toHaveBeenCalledWith(false);
});
it("retries failed archive reads and ignores responses after closing", async () => {
  mocks.list.mockRejectedValueOnce(new Error("Storage unavailable"));
  let resolve!: (value: FixArchivePage) => void;
  mocks.list.mockImplementationOnce(() => new Promise<FixArchivePage>((done) => { resolve = done; }));
  const props = { repositoryId: 1, open: true, onOpenChange: vi.fn(), onSelect: vi.fn() };
  const { rerender } = render(<FixWorkspaceArchive {...props} />);
  await screen.findByText("Storage unavailable");
  await userEvent.click(screen.getByRole("button", { name: "Retry archive" }));
  await waitFor(() => expect(mocks.list).toHaveBeenCalledTimes(2));
  rerender(<FixWorkspaceArchive {...props} open={false} />);
  await act(async () => resolve({ entries: [entry("a".repeat(24), "Late saved task")], nextCursor: null }));
  expect(screen.queryByText("Late saved task")).not.toBeInTheDocument();
});
